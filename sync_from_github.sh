#!/bin/bash
# -----------------------------------------------------------------------
# sync_from_github.sh — 맥북 쪽에서 15분마다 실행 (cron)
# 매주 GitHub 서버에서 업데이트된 위키를 맥북으로 받아옵니다.
# 맥북이 깨어 있을 때만 돌고, 받아올 게 없으면 아무 일도 하지 않습니다.
# Obsidian과 website/index.html 이 자동으로 최신 상태가 됩니다.
# -----------------------------------------------------------------------
cd "$(dirname "$0")" || exit 1
mkdir -p logs
git pull --ff-only -q >> logs/sync.log 2>&1
